#!/bin/bash

# ==============================================================================
# Утилита для проверки здоровья сервера и генерации отчетов
# ==============================================================================

# Дефолтный порог предупреждения в % (если пользователь не передал свой аргумент)
THRESHOLD=80
REPORT_DIR="./health_reports"
REPORT_FILE="$REPORT_DIR/report_$(date +%Y%m%d_%H%M%S).txt"

# ------------- 1. ФУНКЦИИ ЛОГИРОВАНИЯ И КЛАССИЧЕСКИЙ USAGE ---------------

show_usage() {
    echo "Использование: $0 [threshold_percent]"
    echo "Пример: $0 85 (выдаст предупреждение, если диск/память забиты более чем на 85%)"
    exit 1
}

log_msg() {
    local level="$1"
    local message="$2"
    # printf гарантирует, что вывод не сломается из-за скрытых символов
    printf "[%s] [%s] %s\n" "$(date +'%T')" "$level" "$message"
}

# --------------------- 2. ОБРАБОТКА АРГУМЕНТОВ -----------------------------

# Если передан аргумент -h или --help, показываем справку
[ "$1" = "-h" ] || [ "$1" = "--help" ] && show_usage

# Если аргумент передан, перезаписываем порог THRESHOLD
if [ -n "$1" ]; then
    # Проверяем, что передано именно число (базовая валидация)
    if [[ "$1" =~ ^[0-9]+$ ]]; then
        THRESHOLD="$1"
    else
        log_msg "ERROR" "Аргумент должен быть целым числом!"
        exit 1
    fi
fi

log_msg "INFO" "Запуск проверки. Критический порог установлен на: ${THRESHOLD}%"

# ----------------- 3. ПРОВЕРКА УСЛОВИЙ И ДИРЕКТОРИЙ ------------------------

# Проверяем, существует ли папка для отчетов. Если нет - создаем.
if [ ! -d "$REPORT_DIR" ]; then
    log_msg "WARN" "Папка $REPORT_DIR не найдена. Создаем..."
    mkdir -p "$REPORT_DIR" || { log_msg "ERROR" "Не удалось создать папку отчетов"; exit 1; }
fi

# ------------------ 4. СБОР МЕТРИК С ПОМОЩЬЮ AWK -------------------------

log_msg "INFO" "Сбор системных метрик..."

# Получаем % использования корневого диска '/'
DISK_USAGE=$(df -h / | awk 'NR==2 {print $5}' | tr -d '%')

# Получаем % использования оперативной памяти (RAM)
RAM_USAGE=$(free | awk '/Mem:/ {printf "%d", ($3/$2)*100}')

# Получаем среднюю загрузку процессора (Load Average за 1 минуту)
CPU_LOAD=$(uptime | awk -F'load average:' '{print $2}' | awk -F',' '{print $1}' | tr -d ' ')

# --- 5. АНАЛИЗ ДАННЫХ И ПРОВЕРКА ПРЕВЫШЕНИЯ ПОРОГА ---

DISK_STATUS="OK"
RAM_STATUS="OK"

# Проверяем диск (классический if-else)
if [ "$DISK_USAGE" -gt "$THRESHOLD" ]; then
    DISK_STATUS="CRITICAL (Выше ${THRESHOLD}%)"
    log_msg "WARN" "ВНИМАНИЕ: Диск забит на $DISK_USAGE%"
fi

# Проверяем память (сокращенный if через &&)
[ "$RAM_USAGE" -gt "$THRESHOLD" ] && { RAM_STATUS="CRITICAL (Выше ${THRESHOLD}%)"; log_msg "WARN" "ВНИМАНИЕ: Память забита на $RAM_USAGE%"; }

# --- 6. ГЕНЕРАЦИЯ ОТЧЕТА ЧЕРЕЗ CAT << 'EOF' ---

log_msg "INFO" "Запись результатов в файл: $REPORT_FILE"

cat << EOF > "$REPORT_FILE"
==================================================
        ОТЧЕТ О СОСТОЯНИИ СЕРВЕРА
        Дата: $(date +'%Y-%m-%d %H:%M:%S')
==================================================

[Параметры проверки]
Критический порог: ${THRESHOLD}%

[Статистика использования]
1. Использование CPU (Load Avg 1m): $CPU_LOAD
2. Использование RAM: $RAM_USAGE% -> СТАТУС: $RAM_STATUS
3. Использование Диска (/): $DISK_USAGE% -> СТАТУС: $DISK_STATUS

--------------------------------------------------
Отчет сгенерирован автоматически утилитой $0
==================================================
EOF

log_msg "INFO" "Проверка успешно завершена."

